def tr(text: str) -> str:
    """Returns `text` translated to config.LANGUAGE, or `text` unchanged
    if LANGUAGE is "en" (the default) or no Thai entry exists yet."""
    if config.LANGUAGE == "th":
        return TRANSLATIONS.get(text, text)
    return text
