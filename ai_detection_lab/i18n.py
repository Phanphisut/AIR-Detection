"""Tiny translation layer for the app's static UI text (English <-> Thai).

config.LANGUAGE ("en" or "th") is read once, at import time - same as every
other Quick Parameters value in config.py, changing it only takes effect on
the NEXT run of the program. There is no live re-translation of windows
that are already open: this keeps the whole feature a plain "look up this
string" call with no widget-tree walking, no signals, and no risk of a
half-rebuilt window if a retranslation pass were interrupted partway.

Usage: wrap a literal, static English string with tr(...) wherever it is
handed to a Qt widget - tr("Save") instead of "Save". Dynamic text built
with f-strings/.format() (status lines, log messages with live numbers)
is left alone by this pass; only the static chrome (button labels, section
titles, tooltips, dialog titles, static hint text) is translated.

tr() never raises and never blocks up an untranslated string: a key with
no Thai entry yet just falls back to the original English, so a partially
translated screen shows a lesser translation, never a crash or a KeyError.
"""
